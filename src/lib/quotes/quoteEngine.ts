const STORAGE_SESSION_QUOTE = 'becoming_session_quote_v1';
const STORAGE_LAST_QUOTE_ID = 'becoming_last_quote_id';

/**
 * Picks a random quote from the library, avoiding immediate back-to-back repetition.
 */
export function getRandomQuote(excludeId?: string): WisdomQuote {
  const eligible = excludeId
    ? PHILOSOPHICAL_QUOTES.filter((q) => q.id !== excludeId)
    : PHILOSOPHICAL_QUOTES;
  const list = eligible.length > 0 ? eligible : PHILOSOPHICAL_QUOTES;
  const randomIndex = Math.floor(Math.random() * list.length);
  return list[randomIndex];
}

/**
 * Returns the current session's quote. If none exists, selects a fresh non-repeating quote
 * and caches it in sessionStorage.
 */
export function getSessionQuote(): WisdomQuote {
  if (typeof window === 'undefined') {
    return PHILOSOPHICAL_QUOTES[0];
  }

  try {
    const cachedStr = sessionStorage.getItem(STORAGE_SESSION_QUOTE);
    if (cachedStr) {
      const parsed = JSON.parse(cachedStr);
      if (parsed?.quote && parsed?.author) {
        return parsed;
      }
    }

    const lastId = localStorage.getItem(STORAGE_LAST_QUOTE_ID) || undefined;
    const fresh = getRandomQuote(lastId);

    sessionStorage.setItem(STORAGE_SESSION_QUOTE, JSON.stringify(fresh));
    localStorage.setItem(STORAGE_LAST_QUOTE_ID, fresh.id);
    return fresh;
  } catch {
    return PHILOSOPHICAL_QUOTES[0];
  }
}

/**
 * Explicitly replaces the current session quote with a fresh one.
 */
export function rotateSessionQuote(): WisdomQuote {
  if (typeof window === 'undefined') {
    return getRandomQuote();
  }

  try {
    const currentCached = sessionStorage.getItem(STORAGE_SESSION_QUOTE);
    let currentId: string | undefined;
    if (currentCached) {
      try {
        currentId = JSON.parse(currentCached).id;
      } catch {
        // ignore
      }
    }

    const next = getRandomQuote(currentId);
    sessionStorage.setItem(STORAGE_SESSION_QUOTE, JSON.stringify(next));
    localStorage.setItem(STORAGE_LAST_QUOTE_ID, next.id);
    return next;
  } catch {
    return getRandomQuote();
  }
}

/**
 * When BYOK AI is active, requests a custom welcoming reflection tailored to the user's evolution stage.
 * Falls back safely to null on any network or parsing failure.
 */
export async function fetchAiStageGreeting(
  aiSettings: { endpoint?: string; apiKey?: string; model?: string; enabled?: boolean },
  stageName: string,
  stageTagline: string
): Promise<WisdomQuote | null> {
  if (!aiSettings?.enabled || !aiSettings.apiKey?.trim() || !aiSettings.endpoint?.trim()) {
    return null;
  }

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 6000);

  try {
    const prompt = `You are a quiet, poetic, wise companion for the reflection space "BECOMING".
The user has just opened their sanctuary and is currently at Evolution Stage: "${stageName}" (${stageTagline}).
Generate a soothing, beautiful 1-2 sentence welcoming reflection quote and a 2-word theme tailored to their current human chapter.
Respond STRICTLY with a valid JSON object matching this schema:
{
  "quote": "One or two sentences of timeless, gentle wisdom for their session today.",
  "theme": "Two-word theme (e.g. Sovereign Rest, Quiet Spark, Patient Dawn)"
}`;

    const res = await fetch(aiSettings.endpoint, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${aiSettings.apiKey.trim()}`,
      },
      signal: controller.signal,
      body: JSON.stringify({
        model: aiSettings.model?.trim() || 'gpt-4o-mini',
        messages: [
          {
            role: 'system',
            content: 'You provide short, poetic, deeply non-clinical, calming reflection cards. Format strictly as JSON.',
          },
          {
            role: 'user',
            content: prompt,
          },
        ],
        temperature: 0.7,
      }),
    });

    clearTimeout(timeoutId);

    if (!res.ok) {
      return null;
    }

    const data = await res.json();
    const rawContent = data.choices?.[0]?.message?.content;
    if (!rawContent) return null;

    // Parse JSON safely
    const cleaned = rawContent.replace(/```json/g, '').replace(/```/g, '').trim();
    const parsed = JSON.parse(cleaned);

    if (parsed.quote && typeof parsed.quote === 'string') {
      const aiQuote: WisdomQuote = {
        id: `ai_${Date.now()}`,
        quote: parsed.quote.trim(),
        author: 'Sanctuary Mirror',
        theme: parsed.theme?.trim() || 'Session Light',
        isAiGenerated: true,
      };

      try {
        sessionStorage.setItem(STORAGE_SESSION_QUOTE, JSON.stringify(aiQuote));
      } catch {
        // ignore
      }

      return aiQuote;
    }

    return null;
  } catch {
    clearTimeout(timeoutId);
    return null;
  }
}
